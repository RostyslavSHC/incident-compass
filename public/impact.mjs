import {investigate} from './data.mjs';
import {impactCases} from './impact-cases.mjs';

export function createImpactView(escape) {
  const root = document.createElement('section');
  root.className = 'page intro impact-page';
  const modes = ['manual', 'assisted'];
  const labels = {manual:'Manual',assisted:'With Aurelis'};
  const sourceLabels = {telemetry:'Logs & metrics',changes:'Changes',history:'Incident history'};
  let mode = 'manual';
  let round = createRound(false);

  function createRound(swapped) {
    const cases = swapped ? [...impactCases].reverse() : impactCases;
    return Object.fromEntries(modes.map((key,index) => [key,{
      case:cases[index], startedAt:null, duration:null, attempts:0,
      cause:'', check:'', panel:key==='manual' ? 'telemetry' : 'brief', analysis:null,
    }]));
  }

  function time(ms, precise = false) {
    const seconds = (precise ? Math.round(ms / 100) : Math.floor(ms / 1000) * 10) / 10;
    if (seconds < 60) return `${precise ? seconds.toFixed(1) : seconds} s`;
    const minutes = Math.floor(seconds / 60);
    return `${minutes}:${(seconds % 60).toFixed(precise ? 1 : 0).padStart(precise ? 4 : 2,'0')}`;
  }

  const running = run => run.startedAt !== null && run.duration === null;
  const complete = run => run.duration !== null;

  function updateTimer() {
    if (!root.isConnected || !running(round[mode])) return;
    const clock = root.querySelector('[data-impact-clock]');
    const text = time(performance.now() - round[mode].startedAt);
    if (clock.textContent !== text) clock.textContent = text;
  }

  function sourceGroups({incident,archive}) {
    return {
      telemetry:incident.events.filter(item=>item.kind==='Log' || item.kind==='Metric'),
      changes:incident.events.filter(item=>item.kind==='Change' || item.kind==='Maintenance'),
      history:archive,
    };
  }

  function sourceRows(records, group) {
    return `<ul class="impact-records">${records.map(record=>`
      <li data-impact-record="${escape(record.id)}" tabindex="-1">
        <small class="mono quiet">${escape(record.id)} · ${escape(
          group==='history' ? record.fingerprint : `${record.kind} · ${record.time} ET`
        )}</small>
        <h3>${escape(record.title)}</h3>
        <p>${escape(group==='history' ? record.cause : record.detail)}</p>
        ${group==='history' && record.fix ? `<p><strong>Recorded fix</strong> · ${escape(record.fix)}</p>` : ''}
      </li>`).join('')}</ul>`;
  }

  function assistantBrief(analysis, groups) {
    const sources = Object.values(groups).flat();
    const links = [...new Set(analysis.causeSources)].flatMap(id=>{
      const item = sources.find(record=>record.id===id);
      return item ? [`<button type="button" class="ref" data-impact-source="${escape(id)}">${escape(id)}</button>`] : [];
    });
    return `<div class="impact-brief">
      <h3>Likely cause</h3><p>${escape(analysis.cause)}</p>
      ${links.length ? `<div class="references" aria-label="Supporting records">${links.join('')}</div>` : ''}
      <div class="impact-first-check"><h3>First check</h3><p>${escape(analysis.next)}</p></div>
      <details><summary>What could change this assessment?</summary>
        <p>${escape(analysis.challenger.claim)}</p><p>${escape(analysis.challenger.check)}</p>
      </details>
      <small class="quiet">Generated by Aurelis from the records available when this alert fired.</small>
    </div>`;
  }

  function sourcePanel(run) {
    const groups = sourceGroups(run.snapshot);
    const tabs = Object.entries(run.analysis ? {brief:'Aurelis brief',...sourceLabels} : sourceLabels);
    return `<section class="panel impact-panel" aria-labelledby="impact-sources">
      <h2 id="impact-sources">Investigation sources</h2>
      <div class="tabs impact-tabs" role="group" aria-label="Evidence views">
        ${tabs.map(([key,label])=>`<button type="button" class="tab" data-impact-panel="${key}"
          aria-pressed="${run.panel===key}" aria-controls="impact-records">${label}</button>`).join('')}
      </div>
      <div id="impact-records">${run.panel==='brief' ? assistantBrief(run.analysis,groups) : sourceRows(groups[run.panel],run.panel)}</div>
    </section>`;
  }

  function choices(name, label, items, selected) {
    const options = items.map(({id,label})=>`<option value="${escape(id)}" ${id===selected ? 'selected' : ''}>${escape(label)}</option>`);
    return `<label for="impact-${name}">${label}</label>
      <select id="impact-${name}" name="${name}" required>
        <option value="">Choose ${name==='cause' ? 'a likely cause' : 'a first check'}</option>${options.join('')}
      </select>`;
  }

  function investigation(run) {
    const {incident,causes,checks} = run.case;
    return `<section class="impact-alert">
      <div><span class="kicker">HTTP 503 · ${escape(incident.service)}</span>
        <h2 id="impact-stage" tabindex="-1">${escape(incident.title)}</h2>
        <p>${escape(incident.description)}</p>
      </div>
      <div class="impact-clock"><small>Elapsed</small><strong role="timer" data-impact-clock>${time(performance.now()-run.startedAt)}</strong></div>
    </section>
    <div class="impact-columns">
      ${sourcePanel(run)}
      <section class="panel impact-panel" aria-labelledby="impact-decision">
        <h2 id="impact-decision">Record your decision</h2>
        <p class="quiet">Choose the likely cause and the first check you would run.</p>
        <form id="impact-form">
          ${choices('cause','Likely cause',causes,run.cause)}
          ${choices('check','First check',checks,run.check)}
          <p class="impact-feedback" role="alert">${run.attempts ? 'Review the evidence and try another combination. The timer is still running.' : ''}</p>
          <button type="submit" class="primary">Confirm decision</button>
        </form>
      </section>
    </div>`;
  }

  function modeControls() {
    const active = modes.some(key=>running(round[key]));
    return `<div class="impact-modes" role="group" aria-label="Investigation mode">
      ${modes.map(key=>{
        const run = round[key];
        const status = complete(run) ? `Complete · ${time(run.duration,true)}` : running(run) ? 'In progress' : 'Ready';
        return `<button type="button" class="impact-mode" data-impact-mode="${key}" aria-pressed="${key===mode}"
          ${active && key!==mode ? 'disabled' : ''}><strong>${labels[key]}</strong><small>${status}</small></button>`;
      }).join('')}
    </div>`;
  }

  function nextStage(run) {
    if (complete(run)) {
      const next = modes.find(key=>key!==mode);
      const action = next==='assisted' ? 'Continue with Aurelis' : 'Continue to manual investigation';
      return `<section class="panel impact-panel impact-start">
        <h2 id="impact-stage" tabindex="-1">Decision confirmed in ${time(run.duration,true)}</h2>
        <p>Continue to a comparable alert using the other investigation mode.</p>
        <button type="button" class="primary" data-impact-mode="${next}">${action}</button>
      </section>`;
    }
    const guidance = mode==='manual'
      ? 'Review the logs, recent changes and history before recording your decision.'
      : 'Review the automatic Aurelis brief and follow its evidence before recording your decision.';
    return `<section class="panel impact-panel impact-start">
      <h2 id="impact-stage" tabindex="-1">Ready for the ${mode==='manual' ? 'manual' : 'assisted'} run</h2>
      <p>${guidance}</p>
      <button type="button" class="primary" data-impact-start>Receive alert</button>
    </section>`;
  }

  function results() {
    const {manual,assisted} = round;
    const delta = manual.duration - assisted.duration;
    const difference = Math.round(Math.abs(delta)/100)*100;
    const outcome = difference===0 ? 'The runs finished within 0.1 seconds of each other.'
      : `${delta>0 ? 'The assisted run' : 'The manual run'} finished ${time(difference,true)} sooner in this round.`;
    return `<section class="panel impact-panel impact-results">
      <h2 id="impact-stage" tabindex="-1">Time to a supported decision</h2>
      <dl class="impact-result-grid">
        ${modes.map(key=>{
          const run = round[key];
          return `<div><dt>${labels[key]} · ${escape(run.case.incident.service)}</dt>
            <dd class="impact-result-time">${time(run.duration,true)}</dd>
            <dd>${run.attempts===1 ? 'Correct on the first attempt' : `Correct after ${run.attempts} attempts`}</dd>
          </div>`;
        }).join('')}
      </dl>
      <p class="impact-outcome">${outcome}</p>
      <p class="quiet">One participant and two fictional alerts. Run order, practice and case difficulty can affect the result. This measures time to a correct decision during the exercise.</p>
      <button type="button" class="primary" data-impact-swap>Swap cases for a new round</button>
    </section>`;
  }

  function render() {
    const run = round[mode];
    const done = modes.every(key=>complete(round[key]));
    root.innerHTML = `<header class="page-hero impact-hero"><div>
      <h1>Measure investigation impact</h1>
      <p>Compare two fictional HTTP 503 alerts. The timer runs from alert receipt until you choose the supported cause and first check.</p>
    </div></header>
      ${done ? '' : modeControls()}
      ${done ? results() : running(run) ? investigation(run) : nextStage(run)}`;
  }

  function focusStage() {
    root.querySelector('#impact-stage').focus();
  }

  root.addEventListener('change',event=>{
    if (event.target.form?.id==='impact-form') round[mode][event.target.name] = event.target.value;
  });

  root.addEventListener('submit',event=>{
    if (event.target.id!=='impact-form') return;
    event.preventDefault();
    const run = round[mode];
    if (!running(run)) return;
    const decision = new FormData(event.target);
    run.attempts++;
    if (decision.get('cause')!==run.case.correctCause || decision.get('check')!==run.case.correctCheck) {
      root.querySelector('.impact-feedback').textContent = 'Review the evidence and try another combination. The timer is still running.';
      return;
    }
    run.duration = performance.now() - run.startedAt;
    render();
    focusStage();
  });

  root.addEventListener('click',event=>{
    const control = event.target.closest('button');
    if (!control) return;
    const {impactMode,impactPanel,impactSource} = control.dataset;
    const run = round[mode];
    if (impactPanel || impactSource) {
      const group = impactPanel || Object.entries(sourceGroups(run.snapshot))
        .find(([,items])=>items.some(item=>item.id===impactSource))?.[0];
      if (!group || !running(run)) return;
      run.panel = group;
      render();
      const target = impactSource ? `[data-impact-record="${CSS.escape(impactSource)}"]` : `[data-impact-panel="${group}"]`;
      root.querySelector(target)?.focus();
    } else if (impactMode && !running(run)) {
      mode = impactMode;
      render();
      root.querySelector('.impact-mode[aria-pressed="true"]')?.focus();
    } else if (control.hasAttribute('data-impact-start') && run.startedAt===null) {
      run.startedAt = performance.now();
      const {incident,archive} = run.case;
      run.snapshot = {
        incident:{...incident,events:incident.events.filter(item=>item.seenAt<=incident.occurredAt)},
        archive:archive.filter(record=>record.resolvedAt<=incident.occurredAt),
      };
      if (mode==='assisted') run.analysis = investigate(run.snapshot.incident,'23:59',run.snapshot.archive);
      render();
      focusStage();
    } else if (control.hasAttribute('data-impact-swap') && modes.every(key=>complete(round[key]))) {
      round = createRound(round.manual.case===impactCases[0]);
      mode = 'manual';
      render();
      focusStage();
    }
  });

  render();
  return {root, updateTimer};
}
